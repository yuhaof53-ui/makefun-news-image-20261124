#!/usr/bin/env python3
"""Generate the bitmap font data embedded in main.py.

Renders DejaVu Sans Bold (a freely licensed font shipped with the OS)
at two pixel sizes with PIL, thresholds each glyph to 1 bit, and emits a
Python source fragment (FONT = {...}) on stdout. This is a build-time
tool only: the entry program itself is pure standard library and never
reads any font file.

Glyph record: (advance, left, top, width, height, base64_rows)
  advance: horizontal advance in pixels at this size
  left:    glyph bitmap's left edge relative to the pen position
  top:     glyph bitmap's top edge relative to the baseline (negative)
  width/height: bitmap dimensions; rows are bit-packed MSB-first
"""
import base64
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZES = (40, 28)
CHARS = [chr(c) for c in range(32, 127)] + ["\u2014", "\u00b7"]  # printable ASCII + em dash + middot


def render_glyph(font, ch):
    bbox = font.getbbox(ch)
    advance = int(round(font.getlength(ch)))
    if bbox is None:
        return (advance, 0, 0, 0, 0, "")
    left, top, right, bottom = bbox
    w, h = right - left, bottom - top
    if w <= 0 or h <= 0:
        return (advance, left, top, 0, 0, "")
    img = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(img)
    d.text((-left, -top), ch, font=font, fill=255)
    px = img.load()
    rows = bytearray()
    for y in range(h):
        byte = 0
        bits = 0
        for x in range(w):
            byte = (byte << 1) | (1 if px[x, y] >= 128 else 0)
            bits += 1
            if bits == 8:
                rows.append(byte)
                byte = 0
                bits = 0
        if bits:
            rows.append(byte << (8 - bits))
    return (advance, left, top, w, h, base64.b64encode(bytes(rows)).decode("ascii"))


def main():
    out = ["# Bitmap font data, generated by tools/make_font.py from",
           "# DejaVu Sans Bold (free license, /usr/share/fonts/truetype/dejavu/).",
           "# Format: FONT[size][codepoint] = (advance, left, top, w, h, base64_rows)",
           "FONT = {"]
    for size in SIZES:
        font = ImageFont.truetype(FONT_PATH, size)
        ascent, descent = font.getmetrics()
        out.append(f"    {size}: {{  # ascent {ascent}, descent {descent}")
        for ch in CHARS:
            rec = render_glyph(font, ch)
            out.append(f"        {ord(ch)}: {rec!r},")
        out.append("    },")
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
